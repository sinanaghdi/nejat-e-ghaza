const kindLabels: Record<LegalPageKind, string> = {
  privacy: "حریم خصوصی",
  terms: "شرایط استفاده",
  safety: "ایمنی غذا و بازپرداخت",
  security: "امنیت",
  license: "مجوز استفاده",
};

const kindOrder: LegalPageKind[] = ["privacy", "terms", "safety", "security", "license"];

type Props = {
  kind: LegalPageKind;
};

export function LegalPage({ kind }: Props) {
  const document = documents[kind];

  return (
    <main className="legal-page page-shell">
      <nav className="legal-breadcrumb" aria-label="مسیر صفحه">
        <Link to="/">صفحهٔ اصلی</Link>
        <span aria-hidden="true">/</span>
        <span>{document.title}</span>
      </nav>

      <header className="legal-header">
        <p className="eyebrow">نجات غذا · اطلاعات و سیاست‌ها</p>
        <h1>{document.title}</h1>
        <p className="legal-lead">{document.lead}</p>
        <p className="legal-updated">آخرین بازبینی متن: ۱۲ اکتبر ۲۰۲۶</p>
      </header>

      <aside className="legal-notice" role="note">
        <strong>توجه مهم</strong>
        <p>{document.notice}</p>
      </aside>

      <div className="legal-layout">
        <nav className="legal-toc" aria-label="صفحات حقوقی">
          <h2>صفحات اطلاعاتی</h2>
          {kindOrder.map((item) => (
            <Link key={item} to={`/${item}`} className={item === kind ? "active" : ""} aria-current={item === kind ? "page" : undefined}>
              {kindLabels[item]}
            </Link>
          ))}
        </nav>

        <article className="legal-content">
          {document.sections.map((section, index) => (
            <section key={section.title} className="legal-section">
              <h2>{section.title}</h2>
              {section.paragraphs?.map((paragraph) => <p key={paragraph}>{paragraph}</p>)}
              {section.bullets && (
                <ul>
                  {section.bullets.map((bullet) => <li key={bullet}>{bullet}</li>)}
                </ul>
              )}
              {kind === "security" && index === 4 && (
                <p>
                  <a href="https://github.com/sinanaghdi/nejat-e-ghaza/blob/main/SECURITY.md" target="_blank" rel="noreferrer">
                    مطالعهٔ SECURITY.md
                  </a>
                </p>
              )}
              {kind === "license" && index === 3 && (
                <p>
                  <a href="https://github.com/sinanaghdi/nejat-e-ghaza/blob/main/LICENSE" target="_blank" rel="noreferrer">
                    مشاهدهٔ فایل LICENSE
                  </a>
                </p>
              )}
            </section>
          ))}
        </article>
      </div>
    </main>
  );
}
